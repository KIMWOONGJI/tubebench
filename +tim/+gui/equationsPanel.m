function s = num(x)
% shortest exact representation, e.g. 0.98, 20, 1.05, 0.002
s = sprintf('%.10g', x);
end

function s = frac(x)
% two decimals when exact (0.40, 0.01, 0.10), otherwise the shortest form
s = sprintf('%.2f', x);
if abs(str2double(s) - x) > 1e-12, s = num(x); end
end
